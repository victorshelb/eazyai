def build_readme(results: dict, config: dict) -> str:
    task_type = config.get("task_type", "text")
    labels = ", ".join(f"`{l}`" for l in results.get("labels", []))

    if task_type == "image":
        extra = " Pillow"
        usage = " path/to/image.jpg"
        code_example = (
            'classifier = pipeline("image-classification", model="./final_model")\n'
            'from PIL import Image\n'
            'img = Image.open("photo.jpg")\n'
            'print(classifier(img, top_k=3))'
        )
        task_name = "Image Classification"
    else:
        extra = ""
        usage = ""
        code_example = (
            'classifier = pipeline("text-classification", model="./final_model")\n'
            'result = classifier("Your text here", top_k=None)\n'
            'print(result)'
        )
        task_name = "Text Classification"

    return _README.format(
        extra=extra,
        usage=usage,
        code_example=code_example,
        task_name=task_name,
        model_name=results.get("model_name", "—"),
        labels=labels,
        train_samples=results.get("train_samples", 0),
        accuracy=results.get("accuracy", "—"),
        f1_score=results.get("f1_score", "—"),
    )


def get_inference_script(task_type: str) -> str:
    return _IMAGE_INFERENCE_PY if task_type == "image" else _TEXT_INFERENCE_PY


def build_metrics_txt(results: dict, config: dict) -> str:
    lines = [
        "EazyAI — Training Report",
        "=" * 40,
        f"Dataset:    {results.get('dataset_id', '—')}",
        f"Task:       {'Image Classification' if config.get('task_type') == 'image' else 'Text Classification'}",
        f"Model:      {results.get('model_name', '—')}",
        f"Preset:     {results.get('preset', '—')}",
        f"Completed:  {results.get('completed_at', '—')}",
        "",
        "Overall Metrics",
        "-" * 40,
        f"  Accuracy:  {results.get('accuracy', 0):.2f}%",
        f"  F1 Score:  {results.get('f1_score', 0):.4f}",
        f"  Precision: {results.get('precision', 0):.4f}",
        f"  Recall:    {results.get('recall', 0):.4f}",
        "",
    ]

    per_class = results.get("per_class_metrics", {})
    if per_class:
        lines += ["Per-Class Metrics", "-" * 40]
        header = f"  {'Class':<22} {'Precision':>9} {'Recall':>7} {'F1':>7} {'Support':>8}"
        lines.append(header)
        lines.append("  " + "-" * 58)
        for label, vals in per_class.items():
            lines.append(
                f"  {label:<22} {vals.get('precision', 0):>9.4f} {vals.get('recall', 0):>7.4f} "
                f"{vals.get('f1-score', 0):>7.4f} {int(vals.get('support', 0)):>8}"
            )
        lines.append("")

    cm = results.get("confusion_matrix")
    labels = results.get("labels", [])
    if cm and labels:
        lines += ["Confusion Matrix", "-" * 40]
        col_w = max(len(l) for l in labels) + 2
        header = "  " + " " * 22 + "".join(f"{l:>{col_w}}" for l in labels)
        lines.append(header)
        for i, row in enumerate(cm):
            row_str = "".join(f"{v:>{col_w}}" for v in row)
            lines.append(f"  Actual {labels[i]:<14} {row_str}")
        lines.append("")

    cfg = results.get("training_config", {})
    if cfg:
        lines += [
            "Training Config", "-" * 40,
            f"  Epochs:       {cfg.get('num_epochs', '—')}",
            f"  Batch size:   {cfg.get('batch_size', '—')}",
            f"  Learning rate:{cfg.get('learning_rate', '—')}",
            f"  Test split:   {int(cfg.get('test_size', 0.2) * 100)}%",
            f"  Max samples:  {cfg.get('max_samples', '—'):,}",
        ]

    return "\n".join(lines)
