from pathlib import Path
from typing import Dict, Any, List

MODELS_DIR = Path("trained_models")
_cache: Dict[str, Any] = {}


def _model_path(job_id: str) -> Path:
    p = MODELS_DIR / job_id / "final_model"
    if not p.exists():
        raise ValueError(f"Model not found. Make sure training completed successfully.")
    return p


def predict_text(job_id: str, text: str) -> List[Dict]:
    if job_id not in _cache:
        from transformers import pipeline
        _cache[job_id] = pipeline(
            "text-classification",
            model=str(_model_path(job_id)),
            top_k=None,
        )
    results = _cache[job_id](text, top_k=None)
    # The pipeline returns a flat [{label, score}, ...] for a single input,
    # but some versions nest it as [[...]]. Handle both.
    flat = results[0] if results and isinstance(results[0], list) else results
    sorted_results = sorted(flat, key=lambda x: x["score"], reverse=True)
    return [{"label": r["label"], "score": round(r["score"] * 100, 1)} for r in sorted_results]


def predict_image(job_id: str, image_bytes: bytes) -> List[Dict]:
    if job_id not in _cache:
        from transformers import pipeline
        _cache[job_id] = pipeline(
            "image-classification",
            model=str(_model_path(job_id)),
        )
    from PIL import Image
    import io
    img = Image.open(io.BytesIO(image_bytes)).convert("RGB")
    results = _cache[job_id](img, top_k=5)
    return [{"label": r["label"], "score": round(r["score"] * 100, 1)} for r in results]


